"""Configuration: paths, query guard limits and candidate-generation parameters."""

from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parents[2]
DATA_DIR = PROJECT_ROOT / "data"
OUTPUT_DIR = PROJECT_ROOT / "outputs"
REPORT_DIR = PROJECT_ROOT / "reports"
FIG_DIR = REPORT_DIR / "figures"
SQL_DIR = PROJECT_ROOT / "sql"

DB_PATH = DATA_DIR / "shop.db"

#: Hard limits enforced by the read-only executor.
QUERY_TIMEOUT_SECONDS = 5.0
MAX_RESULT_ROWS = 5000

#: Float tolerance used when comparing numeric cells (relative and absolute).
FLOAT_TOLERANCE = 1e-6


@dataclass(frozen=True)
class CandidateConfig:
    """Simulated NL->SQL system version.

    The candidates are **not** produced by an LLM: they are generated by applying
    deterministic SQL mutations to the gold query. ``mutation_rate`` is therefore the
    simulated error rate of that fake system, not a model benchmark.
    """

    name: str
    mutation_rate: float
    seed: int
    syntax_error_questions: tuple[str, ...] = ()


BASELINE = CandidateConfig(name="baseline", mutation_rate=0.45, seed=11,
                           syntax_error_questions=("q07", "q16", "q21"))
IMPROVED = CandidateConfig(name="improved", mutation_rate=0.20, seed=23)
